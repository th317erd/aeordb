/// Selected-database-H profile identity. No allocation, file I/O, source/build
/// hashing or mutable registry lookup occurs. Adding a registered hash requires
/// an independently frozen profile digest and corresponding conformance proof.
/// An unknown retained producer fingerprint does not invalidate its definitions.
pub const fn semantic_compiler_fingerprint_v1(algorithm: HashAlgorithm) -> &'static [u8] {
  match algorithm {
    HashAlgorithm::Blake3_256 => &BLAKE3_256,
    HashAlgorithm::Sha256 => &SHA256,
    HashAlgorithm::Sha512 => &SHA512,
    HashAlgorithm::Sha3_256 => &SHA3_256,
    HashAlgorithm::Sha3_512 => &SHA3_512,
  }
}
